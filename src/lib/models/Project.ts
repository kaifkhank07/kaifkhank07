import mongoose, { Schema, Document } from "mongoose";
import { ProjectService, ProjectCategory } from "@/lib/constants/project";

export interface IProject extends Document {
  title: string;
  slug: string;
  category: string;
  clientName: string;
  services: string[];
  liveDemoLink: string;
  challengeDescription: string;
  showOnHome: boolean;
  visibility: boolean;
  images: string[];
}

const ProjectSchema: Schema = new Schema(
  {
    title: { type: String, required: true },
    slug: { type: String, required: true, unique: true },
    category: {
      type: String,
      required: true,
      enum: Object.values(ProjectCategory),
    },
    clientName: { type: String },
    services: {
      type: [String],
      enum: Object.values(ProjectService),
      default: [],
    },
    liveDemoLink: { type: String },
    challengeDescription: { type: String },
    showOnHome: { type: Boolean, default: false },
    visibility: { type: Boolean, default: false },
    // Stores relative/public paths (e.g., /api/uploads/projects/...) generated by the local server filesystem upload logic instead of S3 URLs
    images: {
      type: [String],
      validate: [
        (val: string[]) => val.length <= 3,
        "A project can have a maximum of 3 images",
      ],
      default: [],
    },
  },
  { timestamps: true }
);

// To prevent Next.js HMR from caching the old schema without showOnHome
if (mongoose.models.Project) {
  delete mongoose.models.Project;
}

export default mongoose.model<IProject>("Project", ProjectSchema);
